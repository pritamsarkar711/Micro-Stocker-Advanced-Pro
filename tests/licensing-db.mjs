// PostgreSQL-level tests. PGlite runs the actual migration with real pgcrypto.
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite({ extensions: { pgcrypto } });
try {
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key, email text, created_at timestamptz default now());
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
    grant usage on schema auth to authenticated, anon;
    grant execute on function auth.uid() to authenticated, anon;`);
  await db.exec(await readFile('supabase/migrations/202611170001_licensing.sql', 'utf8'));
  const admin = '00000000-0000-4000-8000-000000000001';
  const alice = '00000000-0000-4000-8000-000000000002';
  const bob = '00000000-0000-4000-8000-000000000003';
  await db.query('insert into auth.users(id,email) values ($1,$2),($3,$4),($5,$6)', [admin, 'admin@example.test', alice, 'alice@example.test', bob, 'bob@example.test']);
  await db.query('insert into msap_private.admins(user_id) values ($1)', [admin]);
  const asUser = async (id) => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub', $1, false)", [id]); await db.exec('set role authenticated'); };
  await asUser(alice);
  await assert.rejects(db.query("select * from public.msap_create_code(3600, 'premium')"), /Not authorized/);
  await assert.rejects(db.query('select * from msap_private.activation_codes'), /permission denied/);
  await assert.rejects(db.query("select * from public.msap_redeem_code('random')"), /Invalid or unavailable/);
  await asUser(admin);
  const first = (await db.query("select * from public.msap_create_code(3600, 'trial')")).rows[0];
  const second = (await db.query("select * from public.msap_create_code(60, 'premium')")).rows[0];
  assert.match(first.code, /^[A-F0-9]{40}$/);
  assert.notEqual(first.code, second.code);
  await db.query('select public.msap_admin_revoke_code($1)', [second.id]);
  const concurrent = (await db.query("select * from public.msap_create_code(60, 'trial')")).rows[0];
  await asUser(alice);
  await assert.rejects(db.query('select * from public.msap_redeem_code($1)', [second.code]), /Invalid or unavailable/);
  const result = (await db.query('select * from public.msap_redeem_code($1)', [first.code])).rows[0];
  assert.ok(new Date(result.expires_at) - new Date(result.server_time) === 3600000);
  const entitled = (await db.query('select * from public.msap_my_entitlement()')).rows[0];
  assert.ok(new Date(entitled.expires_at) > new Date(entitled.server_time));
  const attempts = await Promise.allSettled([db.query('select * from public.msap_redeem_code($1)', [concurrent.code]), db.query('select * from public.msap_redeem_code($1)', [concurrent.code])]);
  assert.equal(attempts.filter((r) => r.status === 'fulfilled').length, 1, 'only one simultaneous redemption succeeds');
  await asUser(bob);
  await assert.rejects(db.query('select * from public.msap_redeem_code($1)', [first.code]), /Invalid or unavailable/);
  await assert.rejects(db.query('select * from public.msap_admin_users()'), /Not authorized/);
  await asUser(admin);
  await db.query('select public.msap_admin_set_blocked($1, true)', [bob]);
  await assert.rejects(db.query('select public.msap_admin_set_blocked($1, true)', [admin]), /Cannot block your own account/);
  await asUser(bob);
  const blocked = (await db.query('select * from public.msap_my_entitlement()')).rows[0];
  assert.equal(blocked.is_blocked, true);
  await assert.rejects(db.query('select * from public.msap_redeem_code($1)', [second.code]), /Account disabled/);
  await asUser(admin);
  await db.query('select public.msap_admin_set_blocked($1, false)', [bob]);
  await db.query("select public.msap_admin_set_expiry($1, now() - interval '1 second')", [alice]);
  await asUser(alice);
  const expired = (await db.query('select * from public.msap_my_entitlement()')).rows[0];
  assert.ok(new Date(expired.expires_at) < new Date(expired.server_time));
  await db.exec('reset role; set role anon;');
  await assert.rejects(db.query('select * from public.msap_my_entitlement()'), /permission denied/);
  console.log('Licensing SQL: authorization, random codes, redemption, reuse, revocation and expiry passed');
} finally { await db.close(); }
