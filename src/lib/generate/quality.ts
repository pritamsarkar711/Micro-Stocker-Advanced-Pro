/**
 * Pre-delivery quality gate for generated vector artwork.
 *
 * A generation costs the customer credits, so nothing is returned until the
 * geometry, structure and metadata pass these checks. Everything is measured on
 * the actual file, not on the model's claims, and the report is shown to the user
 * with the failed check named.
 */

import { contrastRatio } from './palettes';
import type { Artwork, ArtworkMetadata, ExportFormat } from './engine';

export interface QualityCheck {
  id: string;
  label: string;
  status: 'pass' | 'warn' | 'fail';
  detail: string;
  /** Failing a required check blocks delivery. */
  required: boolean;
}

export interface QualityReport {
  pass: boolean;
  score: number;
  checks: QualityCheck[];
}

const BANNED_WORDS = [
  'ai generated',
  'generated by',
  'midjourney',
  'dall-e',
  'stable diffusion',
  'chatgpt',
  'openai',
  'lorem ipsum',
  'untitled',
  'image of',
  'picture of',
];

const PATH_TOKEN = /^[MLCZ]$/i;
const NUMBER = /^-?\d*\.?\d+$/;

/**
 * Validates path data the way a renderer reads it.
 *
 * Numbers after a command repeat that command implicitly (a second pair after
 * M is a line, a second sextet after C is another curve), so the check tracks a
 * running count per command instead of assuming one coordinate set each.
 */
function pathIsClean(d: string): { ok: boolean; reason?: string } {
  const tokens = d.match(/[MLCZ]|-?\d*\.?\d+/gi) ?? [];
  if (!tokens.length) return { ok: false, reason: 'empty path' };
  if (!/^M/i.test(tokens[0] as string)) return { ok: false, reason: 'path does not start with a move' };

  const arity: Record<string, number> = { M: 2, L: 2, C: 6, Z: 0 };
  let command = '';
  let count = 0;

  const validSegment = () => {
    if (!command) return true;
    const size = arity[command] ?? 0;
    if (size === 0) return count === 0;
    return count > 0 && count % size === 0;
  };

  for (const token of tokens) {
    if (PATH_TOKEN.test(token)) {
      if (!validSegment()) {
        return { ok: false, reason: `short ${command} segment` };
      }
      command = token.toUpperCase();
      count = 0;
      continue;
    }
    if (!NUMBER.test(token)) return { ok: false, reason: `bad number ${token}` };
    count += 1;
  }
  if (!validSegment()) return { ok: false, reason: `incomplete ${command} segment` };
  return { ok: true };
}

const normalise = (d: string) => d.replace(/\s+/g, '').replace(/z/gi, 'Z');

export function checkArtwork(
  art: Artwork,
  meta: ArtworkMetadata,
  format: ExportFormat,
  fileText?: string,
): QualityReport {
  const checks: QualityCheck[] = [];
  const add = (
    id: string,
    label: string,
    status: QualityCheck['status'],
    detail: string,
    required = true,
  ) => checks.push({ id, label, status, detail, required });

  /* ---------------------------------------------------------- geometry */
  const invalid = art.nodes.map((node) => ({ node, result: pathIsClean(node.d) })).filter((entry) => !entry.result.ok);
  add(
    'path-syntax',
    'Path structure',
    invalid.length === 0 ? 'pass' : 'fail',
    invalid.length === 0
      ? `${art.nodes.length} paths parse with closed segments`
      : `${invalid.length} paths are malformed (${invalid[0].result.reason})`,
  );

  const seen = new Set<string>();
  const counts = new Map<string, number>();
  for (const node of art.nodes) {
    const key = normalise(node.d) + (node.fill ?? '') + (node.stroke ?? '');
    counts.set(key, (counts.get(key) ?? 0) + 1);
    seen.add(key);
  }
  // Symmetry legitimately repeats a shape (snowflake arms, laurel leaves, grid
  // tiles); what matters is a shape repeated more than three times outside those
  // deliberately patterned layouts.
  const patterned =
    art.spec.layout === 'grid' ||
    ['line', 'outline', 'geometric'].includes(art.spec.style) ||
    ['snowflake', 'laurel', 'floral', 'diya', 'celebration'].includes(art.spec.motif);
  const overused = patterned ? 0 : Array.from(counts.values()).filter((count) => count > 3).length;
  add(
    'duplicates',
    'No duplicated shapes',
    overused === 0 ? 'pass' : 'warn',
    overused === 0 ? 'every object is unique' : `${overused} shapes repeat more than three times`,
    false,
  );

  const anchors = art.nodes.reduce((total, node) => total + (node.d.match(/[MLC]/gi)?.length ?? 0), 0);
  const perPath = anchors / Math.max(1, art.nodes.length);
  add(
    'anchor-budget',
    'Anchor points',
    anchors <= 2200 && perPath <= 90 ? 'pass' : 'warn',
    `${anchors} points across ${art.nodes.length} paths (${perPath.toFixed(0)} avg)`,
    false,
  );

  add(
    'node-budget',
    'Detail level',
    art.nodes.length >= 8 && art.nodes.length <= 240 ? 'pass' : 'warn',
    `${art.nodes.length} objects`,
    false,
  );

  const offCanvas = art.nodes.filter((node) => {
    const numbers = node.d.match(/-?\d*\.?\d+/g)?.map(Number) ?? [];
    let far = false;
    for (let i = 0; i < numbers.length; i += 2) {
      const x = numbers[i];
      const y = numbers[i + 1];
      if (x < -60 || x > art.width + 60 || y < -60 || y > art.height + 60) far = true;
    }
    return far;
  });
  add(
    'artboard',
    'Inside the artboard',
    offCanvas.length === 0 ? 'pass' : 'fail',
    offCanvas.length === 0 ? 'all geometry within the canvas' : `${offCanvas.length} objects outside the canvas`,
  );

  /* ------------------------------------------------------------ colour */
  const paletteHex = new Set(art.palette.colours.map((colour) => colour.hex.toLowerCase()));
  const used = new Set(
    art.nodes.flatMap((node) => [node.fill, node.stroke].filter((value): value is string => Boolean(value) && value !== 'none').map((value) => value.toLowerCase())),
  );
  const foreign = Array.from(used).filter((hex) => !paletteHex.has(hex));
  add(
    'palette',
    'Colour consistency',
    foreign.length === 0 ? 'pass' : 'fail',
    foreign.length === 0 ? `${used.size} palette colours only` : `off-palette colours: ${foreign.slice(0, 3).join(', ')}`,
  );

  const ink = art.palette.colours[0]?.hex ?? '#000000';
  const paper = art.palette.colours[art.palette.colours.length - 1]?.hex ?? '#ffffff';
  const ratio = contrastRatio(ink, paper);
  add(
    'contrast',
    'Ink and paper contrast',
    ratio >= 3 ? 'pass' : 'warn',
    `${ratio.toFixed(1)}:1`,
    false,
  );

  /* -------------------------------------------------------- composition */
  // `coverage` is already a share of the artboard measured on an occupancy grid.
  const coverage = art.stats.coverage;
  add(
    'coverage',
    'Composition balance',
    coverage >= 0.12 && coverage <= 0.95 ? 'pass' : 'warn',
    `${Math.round(coverage * 100)}% of the canvas is painted`,
    false,
  );

  /* ----------------------------------------------------------- metadata */
  const titleLength = meta.title.length;
  add(
    'title',
    'Title length',
    titleLength >= 15 && titleLength <= 70 ? 'pass' : 'fail',
    `${titleLength} characters (15 to 70 required)`,
  );
  const descriptionLength = meta.description.length;
  add(
    'description',
    'Description length',
    descriptionLength >= 60 && descriptionLength <= 195 ? 'pass' : 'fail',
    `${descriptionLength} characters (60 to 195 required)`,
  );
  add(
    'keywords',
    'Keyword set',
    meta.keywords.length >= 18 && meta.keywords.length <= 45 ? 'pass' : 'fail',
    `${meta.keywords.length} keywords`,
  );
  const lowercase = meta.keywords.every((keyword) => keyword === keyword.toLowerCase());
  const unique = new Set(meta.keywords).size === meta.keywords.length;
  add(
    'keyword-hygiene',
    'Keyword hygiene',
    lowercase && unique ? 'pass' : 'fail',
    lowercase && unique ? 'lowercase, no duplicates' : 'keywords must be lowercase and unique',
  );
  const bannedHits = BANNED_WORDS.filter((word) =>
    `${meta.title} ${meta.description} ${meta.keywords.join(' ')}`.toLowerCase().includes(word),
  );
  add(
    'banned-words',
    'No tool or filler wording',
    bannedHits.length === 0 ? 'pass' : 'fail',
    bannedHits.length === 0 ? 'clean commercial copy' : `remove: ${bannedHits.join(', ')}`,
  );

  /* -------------------------------------------------------------- format */
  if (fileText) {
    const hasRaster = /<image|data:image/i.test(fileText);
    const hasLiveText = /<text[\s>]/i.test(fileText);
    const hasFilter = /<filter|feGaussian|filter=/i.test(fileText);
    add(
      'no-raster',
      'No embedded raster',
      hasRaster ? 'fail' : 'pass',
      hasRaster ? 'raster images are not allowed in vector uploads' : 'pure vector geometry',
    );
    add(
      'no-live-text',
      'Text converted to outlines',
      hasLiveText ? 'fail' : 'pass',
      hasLiveText ? 'live text found' : 'all lettering is editable paths',
    );
    add(
      'no-filters',
      'No effects',
      hasFilter ? 'warn' : 'pass',
      hasFilter ? 'filters can render differently across apps' : 'no filters or blurs',
      false,
    );
    if (format === 'eps' || format === 'ai') {
      const bounding = /%%(HiRes)?BoundingBox: 0 0 [\d.]+ [\d.]+/.test(fileText);
      const eof = /%%EOF\s*$/.test(fileText);
      const header = format === 'ai' ? /%%AI5_FileFormat/.test(fileText) : /%!PS-Adobe-3.0 EPSF-3.0/.test(fileText);
      add(
        'ps-header',
        'PostScript header',
        header && bounding && eof ? 'pass' : 'fail',
        `${format.toUpperCase()} header, bounding box and EOF`,
      );
      const hasVectors = (fileText.match(/moveto/g)?.length ?? 0) >= 8;
      add(
        'ps-vectors',
        'Editable vector content',
        hasVectors ? 'pass' : 'fail',
        `${fileText.match(/moveto/g)?.length ?? 0} drawn paths`,
      );
    }
  }

  const failed = checks.filter((check) => check.required && check.status === 'fail');
  const warnings = checks.filter((check) => !check.required && check.status === 'warn');
  const score = Math.max(
    0,
    Math.round(100 - failed.length * 22 - warnings.length * 4),
  );
  return { pass: failed.length === 0, score, checks };
}
