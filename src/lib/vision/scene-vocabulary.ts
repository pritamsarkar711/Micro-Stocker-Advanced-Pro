/**
 * Vocabulary for the local metadata engine.
 *
 * The point of this file is specificity. A generic list of "commercial" words
 * adds nothing to a buyer search; a landscape needs "horizon, vista, scenery,
 * outdoors", a cutout needs "isolated, transparent background, clipping path".
 * Each scene therefore carries its own nouns, settings and concepts, and the
 * drafting code blends those with the colours and light actually measured in
 * the file.
 */
import type { SceneKind } from './analyse';

export interface SceneProfile {
  /** Title stems; the drafting code appends colour and light context. */
  titles: string[];
  /** Highest value literal keywords, ordered by buyer search intent. */
  keywords: string[];
  /** Broad stock category used when the filename gives nothing better. */
  category: string;
  /** Second category, when a scene genuinely spans two. */
  secondary?: string;
}

